'use client'

import { useCallback, useEffect, useRef, useState, type PointerEvent as ReactPointerEvent } from 'react'
import { createPortal } from 'react-dom'
import posthog from 'posthog-js'

/**
 * The one video pattern for the whole site.
 *
 * By default the tile shows its poster and downloads nothing. Pressing the
 * button opens the lesson full size, with sound, from zero.
 *
 * The hero passes autoplay — there the tile loops muted as an ambient preview.
 * Everywhere else no video is fetched until the button is pressed. See the
 * autoplay prop for why that split exists.
 *
 * The button reads "Watch what your kids will see" in every case. It used to
 * say "Unmute and watch" on the hero, which described the mechanism rather
 * than the offer, and meant the same control was named two different things
 * on one page.
 */
export function VideoTile({
  src,
  loopSrc,
  poster,
  tilePoster,
  title,
  badge,
  blurb,
  location,
  className = '',
  showLabels = true,
  autoplay = false,
  playDisc = false,
  previewSrc,
  captionsUrl,
  ctaHref = '/quiz',
  ctaLabel = 'See more videos like this',
  onHalfway,
  onEnded,
  onOpen,
}: {
  src: string
  loopSrc?: string
  poster?: string
  /**
   * A smaller poster for the TILE only; the modal keeps the full-size one.
   * A tile renders ~320px wide, so a 1280px poster is 3x the bytes for no
   * visible gain — but the modal fills the screen and a soft first frame
   * there is the one place it would show.
   */
  tilePoster?: string
  title: string
  badge?: string
  blurb?: string
  /** Where on the site this tile lives — goes into every event. */
  location: string
  className?: string
  /** Hero uses false: the art alone, no caption furniture. */
  showLabels?: boolean
  /**
   * Muted ambient loop. ONLY the hero should set this true.
   *
   * Measured on a full scroll: the homepage pulled ~82MB, /homeschool ~139MB,
   * and a single blog post ~44MB. At ~2,880 blog visitors a month that was
   * ~127GB of video nobody asked for, on the pages that actually rank — plus
   * a video starting under the eyes of someone who came to read.
   *
   * The hero keeps it because there the video IS the pitch, above the fold,
   * and it is the difference between "here is an app" and "here is what your
   * child would be watching".
   */
  autoplay?: boolean
  /**
   * The big centred green play disc with a "Watch the video" pill under it,
   * instead of the pill button along the bottom edge. Used by the story
   * posts (StoryLesson). The homepage shelf deliberately does NOT use it:
   * it keeps its own white-disc look via .hv2 overrides in home.css
   * (owner's call, Oct 13 2026). Styles: `.video-tile--disc` in globals.css.
   */
  playDisc?: boolean
  /**
   * YouTube-style hover preview: a separate SILENT, low-res, ~7s montage
   * clip (never the real lesson). Desktop: plays after the pointer rests on
   * the tile for 250ms, stops on leave. Touch: plays while the tile is
   * mostly on screen, because hover does not exist there. Nothing is
   * fetched until one of those happens, so a page view costs the same as
   * before; a clip is a few hundred KB against ~30MB for a lesson. Skipped
   * under prefers-reduced-motion and Save-Data. Generated by
   * make-video-previews.py at <mediaBase>/lesson-preview.mp4.
   */
  previewSrc?: string
  captionsUrl?: string
  ctaHref?: string
  ctaLabel?: string
  onHalfway?: () => void
  onEnded?: () => void
  onOpen?: () => void
}) {
  const [open, setOpen] = useState(false)
  const [mounted, setMounted] = useState(false)
  const [near, setNear] = useState(false)
  const [previewing, setPreviewing] = useState(false)
  const [ended, setEnded] = useState(false)
  const hoverTimer = useRef<number | null>(null)
  const wrapRef = useRef<HTMLDivElement>(null)
  const tileRef = useRef<HTMLVideoElement>(null)
  const modalRef = useRef<HTMLVideoElement>(null)
  const halfFired = useRef(false)

  useEffect(() => setMounted(true), [])

  // Only autoplaying tiles need to fetch on approach. A poster-first tile
  // downloads nothing until the button is pressed.
  useEffect(() => {
    if (!autoplay) return
    const el = wrapRef.current
    if (!el || typeof IntersectionObserver === 'undefined') { setNear(true); return }
    const io = new IntersectionObserver(
      ([entry]) => {
        if (entry.isIntersecting) setNear(true)
        const v = tileRef.current
        if (!v) return
        if (entry.isIntersecting) v.play().catch(() => { /* autoplay policy */ })
        else v.pause()
      },
      { rootMargin: '300px' },
    )
    io.observe(el)
    return () => io.disconnect()
  }, [autoplay])

  // Hover / in-view preview. Only when previewSrc is given and the tile is not
  // already an ambient loop (the hero), and never for people who asked for
  // less motion or less data.
  const previewAllowed = Boolean(previewSrc) && !autoplay
  const previewOk = useCallback(() => {
    if (!previewAllowed || typeof window === 'undefined') return false
    if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) return false
    const conn = (navigator as Navigator & { connection?: { saveData?: boolean } }).connection
    if (conn?.saveData) return false
    return true
  }, [previewAllowed])

  const startPreview = useCallback(() => {
    if (!previewOk() || open) return
    setPreviewing(true)
  }, [previewOk, open])
  const stopPreview = useCallback(() => {
    if (hoverTimer.current) { window.clearTimeout(hoverTimer.current); hoverTimer.current = null }
    setPreviewing(false)
  }, [])

  // Pointer: YouTube waits a beat so a mouse crossing the page does not fire
  // a download for every tile it passes.
  const onPointerEnter = useCallback((e: ReactPointerEvent) => {
    if (e.pointerType !== 'mouse') return
    if (hoverTimer.current) window.clearTimeout(hoverTimer.current)
    hoverTimer.current = window.setTimeout(startPreview, 250)
  }, [startPreview])
  const onPointerLeave = useCallback((e: ReactPointerEvent) => {
    if (e.pointerType !== 'mouse') return
    stopPreview()
  }, [stopPreview])

  // Touch: no hover, so the preview runs while the tile is mostly on screen,
  // which is how YouTube's feed behaves on a phone.
  useEffect(() => {
    if (!previewAllowed) return
    if (typeof window === 'undefined' || window.matchMedia('(hover: hover)').matches) return
    const el = wrapRef.current
    if (!el || typeof IntersectionObserver === 'undefined') return
    const io = new IntersectionObserver(
      ([entry]) => { if (entry.isIntersecting) startPreview(); else stopPreview() },
      { threshold: 0.6 },
    )
    io.observe(el)
    return () => io.disconnect()
  }, [previewAllowed, startPreview, stopPreview])

  // Drive the <video>: play from zero when previewing, pause and rewind to
  // the poster when not.
  useEffect(() => {
    const v = tileRef.current
    if (!v || !previewAllowed) return
    if (previewing) {
      v.currentTime = 0
      v.play().catch(() => { /* autoplay policy: the poster stays */ })
    } else {
      v.pause()
      try { v.currentTime = 0 } catch { /* not loaded yet */ }
    }
  }, [previewing, previewAllowed])

  const openPlayer = useCallback(() => {
    stopPreview()
    tileRef.current?.pause()
    setNear(true)
    setEnded(false)
    setOpen(true)
    onOpen?.()
    try { posthog.capture('video_expanded', { title, location }) } catch { /* never break playback */ }
  }, [title, location, onOpen, stopPreview])

  const closePlayer = useCallback(() => {
    setOpen(false)
    setEnded(false)
    tileRef.current?.play().catch(() => { /* autoplay policy */ })
  }, [])

  const replay = useCallback(() => {
    const el = modalRef.current
    setEnded(false)
    if (el) { el.currentTime = 0; el.play().catch(() => { /* controls are there */ }) }
    try { posthog.capture('video_replay', { title, location }) } catch { /* never break */ }
  }, [title, location])

  // Always from the beginning, always with sound.
  useEffect(() => {
    if (!open) return
    const el = modalRef.current
    if (el) {
      el.currentTime = 0
      el.muted = false
      el.play().catch(() => { /* the controls are right there */ })
    }
    const prev = document.body.style.overflow
    document.body.style.overflow = 'hidden'
    const onKey = (e: KeyboardEvent) => { if (e.key === 'Escape') closePlayer() }
    window.addEventListener('keydown', onKey)
    return () => {
      document.body.style.overflow = prev
      window.removeEventListener('keydown', onKey)
    }
  }, [open, closePlayer])

  return (
    <div
      ref={wrapRef}
      className={`video-tile ${playDisc ? 'video-tile--disc' : ''} ${previewing ? 'is-previewing' : ''} ${className}`.replace(/\s+/g, ' ').trim()}
      onPointerEnter={previewAllowed ? onPointerEnter : undefined}
      onPointerLeave={previewAllowed ? onPointerLeave : undefined}
    >
      <div className="video-tile-screen">
        <video
          ref={tileRef}
          src={autoplay && near ? (loopSrc || src) : (previewAllowed && previewing ? previewSrc : undefined)}
          poster={tilePoster || poster}
          autoPlay={autoplay}
          muted
          loop={autoplay || previewing}
          playsInline
          preload={(autoplay && near) || previewing ? 'metadata' : 'none'}
          className="video-tile-video"
        />

        {showLabels && (title || badge) && (
          <div className="video-tile-overlay">
            <span className="video-tile-title">{title}</span>
            {badge && <span className="video-tile-badge">{badge}</span>}
          </div>
        )}

        {playDisc ? (
          /* The disc, the label and a soft scrim are real elements, not
             pseudo-elements over hidden text. The first version used
             display:grid with the old label text still in the DOM at
             font-size:0 - grid gave that invisible text its own row, split
             the height between the two rows, and the disc centred in the
             TOP half (about 38% down on every tile). Owner saw it at once. */
          <button
            className="video-tile-btn"
            onClick={openPlayer}
            aria-label={title ? `Watch the video: ${title}` : 'Watch the video'}
          >
            <span className="video-tile-disc" aria-hidden="true" />
            <span className="video-tile-disc-label">Watch the video</span>
          </button>
        ) : (
          /* Three tiles side by side otherwise all announce "Watch what your
             kids will see", which tells a screen reader user nothing about
             which story they are opening. The label KEEPS the visible text
             and appends the title: an accessible name that drops the words
             on the button breaks voice control, and axe flags it
             (label-content-name-mismatch). */
          <button
            className="video-tile-btn"
            onClick={openPlayer}
            aria-label={title ? `${'\u25B6'} Watch what your kids will see: ${title}` : undefined}
          >
            {`${'\u25B6'} Watch what your kids will see`}
          </button>
        )}
      </div>

      {mounted && open && createPortal(
        <div className="vid-modal" role="dialog" aria-modal="true" aria-label={title}>
          <button className="vid-modal-scrim" aria-label="Close video" onClick={closePlayer} />
          <div className="vid-modal-inner">
            <button className="vid-modal-close" onClick={closePlayer} aria-label="Close video">&times;</button>
            <div className="vid-modal-stage">
              <video
                ref={modalRef}
                src={src}
                poster={poster}
                controls
                playsInline
                className="vid-modal-video"
                onPlay={() => setEnded(false)}
                onTimeUpdate={e => {
                  const v = e.currentTarget
                  if (!halfFired.current && v.duration && v.currentTime / v.duration >= 0.5) {
                    halfFired.current = true
                    onHalfway?.()
                  }
                }}
                onEnded={() => {
                  setEnded(true)
                  onEnded?.()
                  try { posthog.capture('video_end_screen_shown', { title, location }) } catch { /* never break */ }
                }}
              >
                {captionsUrl && (
                  <track kind="captions" src={captionsUrl} srcLang="en" label="English" default />
                )}
              </video>

              {/* End screen: the moment of peak intent is the second the
                  story finishes, with the child still watching. The native
                  controls underneath are untouched; "Watch again" is the
                  only thing that hides this. */}
              {ended && (
                <div className="vid-end" role="group" aria-label="Video finished">
                  <p className="vid-end-kicker">That was {title}</p>
                  <h3 className="vid-end-title">Want to see more stories like this?</h3>
                  <p className="vid-end-sub">300+ Bible stories, about two minutes each, with a quiz after every one.</p>
                  <a
                    href={ctaHref}
                    className="vid-end-cta"
                    onClick={() => {
                      try { posthog.capture('video_cta_click', { title, location, placement: 'end_screen' }) } catch { /* never break */ }
                    }}
                  >
                    {ctaLabel}
                  </a>
                  <button type="button" className="vid-end-replay" onClick={replay}>Watch again</button>
                </div>
              )}
            </div>
            <div className="vid-modal-meta">
              {badge && <span className="vid-modal-series">{badge}</span>}
              <strong>{title}</strong>
              {blurb && <p>{blurb}</p>}
              <a
                href={ctaHref}
                className="btn-primary"
                onClick={() => {
                  try { posthog.capture('video_cta_click', { title, location }) } catch { /* never break */ }
                }}
              >
                {ctaLabel}
              </a>
            </div>
          </div>
        </div>,
        document.body
      )}
    </div>
  )
}
